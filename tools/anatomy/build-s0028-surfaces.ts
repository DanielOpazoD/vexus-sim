/** Offline only: index the unchanged native-lattice marching-cubes stream, bit for bit. */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gunzipSync, gzipSync } from 'node:zlib';
import { S0028_BUNDLE as B } from '../../src/anatomy/anatomyBundle';
import { sourceSurface } from '../../src/anatomy/sourceSurface';

const hash = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');
function atlas(asset: 'abdominal' | 'thoracic'): Uint16Array {
  const compressed = readFileSync(`src/anatomy/s0028/${asset}-direct.gzip.bin`);
  const raw = gunzipSync(compressed),
    meta = B[asset];
  if (
    compressed.length !== meta.gzipBytes ||
    hash(compressed) !== meta.sha256Gzip ||
    raw.length !== meta.rawBytes ||
    hash(raw) !== meta.sha256Raw
  )
    throw new Error('Fuente s0028 alterada');
  return new Uint16Array(raw.buffer, raw.byteOffset, raw.byteLength / 2);
}
const data = { abdominal: atlas('abdominal'), thoracic: atlas('thoracic') };
const arrays: Uint8Array[] = [],
  fields = [];
let offset = 0;
for (const f of B.fields) {
  const source = await sourceSurface(data[f.asset], f, B[f.asset].textureDimensions);
  const bits = new Uint32Array(source.positions.buffer),
    vertices: number[] = [],
    indices = new Uint32Array(bits.length / 3);
  const ids = new Map<string, number>();
  for (let i = 0; i < bits.length; i += 3) {
    const key = `${bits[i]},${bits[i + 1]},${bits[i + 2]}`;
    let id = ids.get(key);
    if (id === undefined) {
      id = vertices.length / 3;
      ids.set(key, id);
      vertices.push(bits[i], bits[i + 1], bits[i + 2]);
    }
    indices[i / 3] = id;
  }
  const positions = new Uint32Array(vertices);
  // Exhaustive proof, not a geometric sampling: every expanded component must be identical.
  for (let i = 0; i < indices.length; i++)
    for (let a = 0; a < 3; a++) if (positions[3 * indices[i] + a] !== bits[3 * i + a]) throw new Error('Triángulo alterado');
  fields.push({
    name: f.name,
    asset: f.asset,
    positionOffset: offset,
    vertexCount: positions.length / 3,
    indexOffset: offset + positions.byteLength,
    indexCount: indices.length,
    expandedSha256: hash(new Uint8Array(source.positions.buffer)),
  });
  arrays.push(new Uint8Array(positions.buffer), new Uint8Array(indices.buffer));
  offset += positions.byteLength + indices.byteLength;
  console.log(f.name, 'triangles', indices.length / 3, 'vertices', positions.length / 3);
}
const raw = new Uint8Array(offset);
let at = 0;
for (const bytes of arrays) {
  raw.set(bytes, at);
  at += bytes.length;
}
const gzip = gzipSync(raw, { level: 9 });
const meta = {
  person: B.person,
  frameId: B.frameId,
  revision: B.revision,
  units: 'mm',
  format: 'indexed-f32-u32-v1',
  sourceBundleSha256: hash(new TextEncoder().encode(JSON.stringify(B))),
  rawBytes: raw.length,
  gzipBytes: gzip.length,
  sha256Raw: hash(raw),
  sha256Gzip: hash(gzip),
  fields,
};
writeFileSync('src/anatomy/s0028/surfaces.gzip.bin', gzip);
writeFileSync(
  'src/anatomy/s0028SurfaceData.ts',
  '/** Generated by tools/anatomy/build-s0028-surfaces.ts; native zero, exact triangles. */\nexport const S0028_SURFACE = ' +
    JSON.stringify(meta) +
    ' as const;\n',
);
console.log(JSON.stringify(meta));
